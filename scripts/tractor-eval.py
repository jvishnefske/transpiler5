#: Ranked worst-first for the failure table; PASS is not a failure.
OUTCOME_ORDER = [PASS, VACUOUS_PASS, VECTOR_FAIL, SYMBOL_MISSING,
                 HARNESS_ERROR, BUILD_FAIL, EMIT_FAIL, NOT_DISCOVERED]

_LIBRARY_RX = re.compile(r'^\s*library:\s*"([^"]+)"', re.MULTILINE)
_SYMBOL_RX = re.compile(r'^\s*symbol:\s*"([^"]+)"', re.MULTILINE)


@dataclass
class Case:
    """One evaluable corpus case."""

    rel_name: str            # e.g. "Public-Tests/B01_organic/crc16_lib"
    root: Path               # <corpus>/<rel_name>
    is_library: bool
    glob_sources: list       # .c paths found by scan (fallback; never empty)
    glob_include_dirs: list  # -I directories for the fallback path
    library: Optional[str]   # _lib only: the lib<NAME>.so the harness dlopens
    symbol: Optional[str]    # _lib only: the bare symbol it dlsyms
    naming: str              # "explicit" | "derived" | "n/a"
    cmake_source_dir: Path   # what to pass to `cmake -S`
    cache_vars: dict         # CMakePresets "test" cache variables

    @property
    def crate_dir(self) -> Path:
        return self.root / "translated_rust"

    @property
    def crate_name(self) -> str:
        """Also the CMake target name: verified to coincide for every case."""
        return self.library if self.is_library else "driver"


@dataclass
class Result:
    """One measured case."""

    case: Case
    outcome: str = EMIT_FAIL
    detail: str = ""
    emit_cmd: list = field(default_factory=list)
    emit_rc: Optional[int] = None
    emit_stderr: str = ""
    vectors_passed: int = 0
    vectors_failed: int = 0
    vectors_skipped: int = 0
    vector_failures: list = field(default_factory=list)  # (name, message)
    symbol_present: Optional[bool] = None
    artifact: str = ""
    source_mode: str = ""        # "compdb" (the case's own flags) or "glob"
    sources: list = field(default_factory=list)
    detail_prefix: str = ""

    def as_dict(self) -> dict:
        return {
            "case": self.case.rel_name,
            "kind": "lib" if self.case.is_library else "exec",
            "outcome": self.outcome,
            "detail": self.detail,
            "library": self.case.library,
            "symbol": self.case.symbol,
            "naming": self.case.naming,
            "source_mode": self.source_mode,
            "sources": self.sources,
            "emit_rc": self.emit_rc,
            "emit_stderr": self.emit_stderr,
            "emit_cmd": self.emit_cmd,
            "vectors_passed": self.vectors_passed,
            "vectors_failed": self.vectors_failed,
            "vectors_skipped": self.vectors_skipped,
            "vector_failures": [
                {"vector": n, "message": m} for n, m in self.vector_failures
            ],
            "symbol_present": self.symbol_present,
            "artifact": self.artifact,
        }


def tail(text: str, n: int = 12) -> str:
    lines = [l for l in (text or "").splitlines() if l.strip()]
    return "\n".join(lines[-n:])


_PROGRESS_RX = re.compile(r"^\[\d+/\d+\] Processing file ")


def emit_diagnostics(stderr: str, n: int = 24) -> str:
    """The diagnostics from an emitrust-cc run, without its progress chatter.

    A multi-TU import prints one progress line per file, so a plain tail of a
    128-file project's stderr is all progress and no diagnosis. Errors are
    kept in the order emitted -- the FIRST located rejection is the one that
    explains the failure; a later "failed to parse one or more C inputs" is
    only its summary.
    """
    lines = [l for l in (stderr or "").splitlines()
             if l.strip() and not _PROGRESS_RX.match(l)]
    errors = [l for l in lines if re.search(r"\b(error|fatal error):", l)]
    if errors:
        return "\n".join(errors[:n])
    return "\n".join(lines[-n:])


