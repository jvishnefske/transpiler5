def main() -> int:
    ap = argparse.ArgumentParser(
        description=__doc__.splitlines()[0],
        formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("corpus", type=Path,
                    help="root of the (separately cloned) TRACTOR corpus")
    ap.add_argument("--emitrust-cc", type=Path,
                    default=Path("build/tools/emitrust-cc"),
                    help="path to the emitrust-cc driver")
    ap.add_argument("--out", type=Path, default=None,
                    help="report directory (default <corpus>/../tractor-eval-out)")
    ap.add_argument("-j", "--jobs", type=int, default=os.cpu_count(),
                    help="parallel emit and build jobs")
    ap.add_argument("-m", "--match", default=None,
                    help="only evaluate cases whose rel path matches this regex")
    ap.add_argument("--no-diffs", action="store_true",
                    help="skip the verbose re-run that collects failure diffs")
    ap.add_argument("--extra-cflags", default="",
                    help="appended to CMAKE_C_FLAGS when configuring each case; "
                         "use it to supply a host dependency the corpus needs "
                         "but the machine lacks (the SPHINCS+ exec cases "
                         "#include <openssl/*.h>)")
    args = ap.parse_args()

    corpus = args.corpus.resolve()
    cc = args.emitrust_cc.resolve()
    if not cc.is_file():
        sys.exit(f"error: emitrust-cc not found at {cc}")
    out_dir = (args.out or (corpus.parent / "tractor-eval-out")).resolve()
    out_dir.mkdir(parents=True, exist_ok=True)

    cases, skipped = discover(corpus)
    if args.match:
        rx = re.compile(args.match)
        cases = [c for c in cases if rx.search(c.rel_name)]
    if not cases:
        sys.exit("error: no evaluable cases discovered")
    print(f"discovered {len(cases)} evaluable cases "
          f"({len(skipped)} case dirs have no .c and are excluded)")

    # Stale translated_rust from an earlier run of a DIFFERENT case selection
    # would still be discovered by the corpus runner and scored. Wipe every
    # one, not just the selected cases.
    for bundle in sorted((corpus / "Public-Tests").iterdir()):
        if bundle.is_dir():
            for root in bundle.iterdir():
                if root.is_dir():
                    shutil.rmtree(root / "translated_rust", ignore_errors=True)

    print(f"emitting with {cc} ...")
    start = time.time()
    with ThreadPoolExecutor(max_workers=args.jobs) as pool:
        results = list(pool.map(
            lambda c: emit(c, cc, out_dir, args.extra_cflags), cases))
    emitted = [r for r in results if r.outcome != EMIT_FAIL]
    print(f"emitted {len(emitted)}/{len(cases)} crates in {time.time() - start:.1f}s")

    junit = out_dir / "junit.xml"
    if junit.exists():
        junit.unlink()
    if emitted:
        print("running the corpus's own runner (build + test) ...")
        start = time.time()
        rc, output = run_corpus(corpus, junit, [], False, args.jobs,
                                out_dir / "runner.log")
        print(f"corpus runner exited {rc} in {time.time() - start:.1f}s")
        if not junit.is_file():
            print("error: the corpus runner wrote no JUnit report; last output:",
                  file=sys.stderr)
            print(tail(output, 40), file=sys.stderr)
            return 2

    junit_by_case = parse_junit(junit)
    for r in results:
        # Artifacts first: classify() must know whether the symbol the harness
        # dlsyms actually exists before it can call a failure "wrong output"
        # rather than "never ran".
        if r.outcome != EMIT_FAIL:
            check_artifacts(r)
        classify(r, junit_by_case.get(r.case.rel_name))
    for r in results:
        if r.outcome == BUILD_FAIL:
            diagnose_build_failure(r)

    # The runner's non-verbose messages carry no diff. Re-run just the cases
    # that produced wrong bytes, verbose and test-only, to capture the corpus's
    # OWN diff for each -- these are the potential miscompiles.
    wrong = [r for r in results if r.outcome == VECTOR_FAIL]
    if wrong and not args.no_diffs:
        print(f"re-running {len(wrong)} wrong-output case(s) verbosely for diffs ...")
        pattern = "|".join(re.escape(r.case.rel_name) for r in wrong)
        vjunit = out_dir / "junit-verbose.xml"
        run_corpus(corpus, vjunit, ["--only", "test", "-m", pattern], True,
                   args.jobs, out_dir / "runner-verbose.log")
        verbose_by_case = parse_junit(vjunit)
        for r in wrong:
            rec = verbose_by_case.get(r.case.rel_name)
            if not rec:
                continue
            detailed = [(n, m) for n, s, m in rec["vectors"] if s == "failed"]
            if detailed:
                r.vector_failures = detailed

    write_reports(out_dir, results, skipped, len(junit_by_case))
    summarize(results, skipped, out_dir)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
