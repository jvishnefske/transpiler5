def preset_cache_vars(case_root: Path) -> dict:
    """Cache variables of the case's ``test`` configure preset, if any.

    The SPHINCS+ cases are 128 distinct cases over ONE source tree; what makes
    them distinct lives entirely in ``CMakePresets.json`` (``HASH_BACKEND``,
    ``SECPAR``, ``THASH``), which the corpus's own configure applies with
    ``--preset test``. This resolves the same variables by hand so the
    configure does not need cmake's preset generator (Ninja) to be installed.
    """
    presets = case_root / "CMakePresets.json"
    if not presets.is_file():
        return {}
    try:
        data = json.loads(presets.read_text(encoding="utf-8"))
    except (OSError, ValueError):
        return {}
    by_name = {p.get("name"): p for p in data.get("configurePresets", [])}

    def resolve(name, seen=()):
        preset = by_name.get(name)
        if preset is None or name in seen:
            return {}
        out = {}
        inherits = preset.get("inherits") or []
        if isinstance(inherits, str):
            inherits = [inherits]
        for parent in inherits:
            out.update(resolve(parent, seen + (name,)))
        out.update({k: str(v) for k, v in
                    (preset.get("cacheVariables") or {}).items()})
        return out

    return resolve("test")


def cmake_configure(case: Case, out_dir: Path, extra_cflags: str) -> tuple:
    """Configure the case's CMake project with the file API. (build|None, err).

    Mirrors the corpus's own C-mode configure (``runtests/build.py``:
    ``configure_c_test_case``) -- same project, same ``clang``, same preset
    cache variables -- so the sources and macros are the ones the case's
    reference build uses rather than a guess. Uses the Makefiles generator
    because it is always available; nothing is ever built here.
    """
    build = out_dir / "cdb" / case.rel_name.replace("/", "__")
    shutil.rmtree(build, ignore_errors=True)
    (build / ".cmake" / "api" / "v1" / "query").mkdir(parents=True, exist_ok=True)
    (build / ".cmake" / "api" / "v1" / "query" / "codemodel-v2").touch()
    cmd = ["cmake", "-S", str(case.cmake_source_dir), "-B", str(build),
           "-G", "Unix Makefiles", "-DCMAKE_C_COMPILER=clang",
           "-DCMAKE_EXPORT_COMPILE_COMMANDS=ON"]
    if extra_cflags:
        cmd.append(f"-DCMAKE_C_FLAGS={extra_cflags}")
    cmd += [f"-D{k}={v}" for k, v in case.cache_vars.items()]
    try:
        proc = subprocess.run(cmd, capture_output=True, text=True,
                              timeout=CMAKE_TIMEOUT)
    except subprocess.TimeoutExpired:
        return None, "cmake configure timed out"
    if proc.returncode != 0 or not (build / "compile_commands.json").is_file():
        return None, "cmake configure failed: " + tail(proc.stderr or proc.stdout, 6)
    return build, ""


def target_closure(build: Path, target: str) -> tuple:
    """Source files of ``target`` plus its transitive link closure. (set|None, err).

    Read from CMake's file API rather than from the compile database, because
    the database says which files are compiled in the PROJECT and not which
    ones make up the ONE artifact the corpus tests. A SPHINCS+ ``_lib`` case
    tests ``libblake.so``, five of the project's fourteen translation units;
    handing the transpiler all fourteen would emit a crate full of duplicate
    definitions for four different hash backends.
    """
    reply = build / ".cmake" / "api" / "v1" / "reply"
    indexes = sorted(reply.glob("index-*.json"))
    if not indexes:
        return None, "cmake file API produced no index"
    index = json.loads(indexes[-1].read_text(encoding="utf-8"))
    codemodels = [o for o in index.get("objects", [])
                  if o.get("kind") == "codemodel"]
    if not codemodels:
        return None, "cmake file API produced no codemodel"
    model = json.loads((reply / codemodels[0]["jsonFile"]).read_text(encoding="utf-8"))
    source_root = Path(model["paths"]["source"])
    by_id, by_name = {}, {}
    for cfg in model.get("configurations", []):
        for entry in cfg.get("targets", []):
            target_json = json.loads((reply / entry["jsonFile"]).read_text(encoding="utf-8"))
            by_id[entry["id"]] = target_json
            by_name.setdefault(target_json["name"], target_json)
    if target not in by_name:
        return None, (f"cmake target {target!r} not found "
                      f"(have: {', '.join(sorted(by_name)) or 'none'})")

    seen, sources = set(), set()
    stack = [by_name[target]]
    while stack:
        node = stack.pop()
        if node["id"] in seen:
            continue
        seen.add(node["id"])
        for src in node.get("sources", []):
            path = Path(src["path"])
            if path.suffix != ".c":
                continue  # object-library artifacts arrive via `dependencies`
            sources.add(str(path if path.is_absolute() else source_root / path))
        for dep in node.get("dependencies", []):
            dep_target = by_id.get(dep.get("id"))
            if dep_target is not None:
                stack.append(dep_target)
    if not sources:
        return None, f"cmake target {target!r} has no C sources"
    return sources, ""


def filtered_compdb(build: Path, sources: set, target: str,
                    out_path: Path) -> tuple:
    """Write the compile-database entries for exactly ``sources``. (path|None, err).

    ONE entry per source file. A file that several CMake targets compile (the
    SPHINCS+ tree shares ``app/src/utils.c`` between its core and every hash
    backend) appears in the database once per target, and handing the same
    translation unit to the transpiler twice is not a duplicate that later
    de-duplicates -- it is two definitions of every symbol in it. The entry
    built for ``target`` wins; otherwise the first.
    """
    db = json.loads((build / "compile_commands.json").read_text(encoding="utf-8"))
    wanted = {os.path.realpath(s) for s in sources}
    marker = f"CMakeFiles/{target}.dir/"
    chosen = {}
    for entry in db:
        real = os.path.realpath(entry["file"])
        if real not in wanted:
            continue
        preferred = marker in (entry.get("output") or entry.get("command", ""))
        if real not in chosen or (preferred and not chosen[real][0]):
            chosen[real] = (preferred, entry)
    entries = [e for _, e in chosen.values()]
    missing = wanted - set(chosen)
    if missing:
        return None, ("no compile command for "
                      + ", ".join(sorted(os.path.basename(m) for m in missing)))
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(entries, indent=1), encoding="utf-8")
    return out_path, ""


def emit(case: Case, cc: Path, out_dir: Path, extra_cflags: str) -> Result:
    """Emit ``<case>/translated_rust``. Strict mode: no recovery, no partials."""
    res = Result(case=case)

    # GUARD: a case with no sources must never reach the corpus runner. It is
    # rejected here, before emitrust-cc runs, so no zero-iteration loop can
    # fall through to a success.
    if not case.glob_sources:
        res.outcome, res.detail = EMIT_FAIL, "no-sources"
        return res

    # GUARD: wipe the whole crate directory, target/ included, so no shared
    # object or binary from an earlier run under a different --crate-name can
    # be dlopened and scored.
    shutil.rmtree(case.crate_dir, ignore_errors=True)

    cmd = [str(cc), "--emit=crate", f"--crate-name={case.crate_name}",
           "--crate-type=" + ("lib" if case.is_library else "bin")]
    if case.is_library:
        cmd.append("--c-abi-exports")
    cmd += ["-o", str(case.crate_dir)]

    build, err = cmake_configure(case, out_dir, extra_cflags)
    sources = None
    if build is not None:
        sources, err = target_closure(build, case.crate_name)
    if sources is not None:
        db, err = filtered_compdb(
            build, sources, case.crate_name,
            out_dir / "compdb" / (case.rel_name.replace("/", "__") + ".json"))
        if db is not None:
            res.source_mode = "compdb"
            res.sources = sorted(sources)
            cmd.append(f"--compdb={db}")
    if res.source_mode != "compdb":
        # Fallback: glob. Recorded, so a number can never be read as
        # "the corpus's own flags" when it was not.
        res.source_mode = "glob"
        res.detail_prefix = f"[glob fallback: {err}] "
        res.sources = list(case.glob_sources)
        for inc in case.glob_include_dirs:
            cmd += ["-I", inc]
        cmd += case.glob_sources

    res.emit_cmd = cmd
    try:
        proc = subprocess.run(cmd, cwd=str(case.root), capture_output=True,
                              text=True, timeout=EMIT_TIMEOUT)
    except subprocess.TimeoutExpired:
        shutil.rmtree(case.crate_dir, ignore_errors=True)
        res.outcome, res.detail = EMIT_FAIL, "emit timed out"
        return res

    res.emit_rc = proc.returncode
    res.emit_stderr = emit_diagnostics(proc.stderr)

    # GUARD: emitrust-cc exits 1 having done NOTHING on an unknown flag, which
    # looks exactly like success if you only inspect output. Check the code
    # AND the artifact.
    if proc.returncode != 0:
        shutil.rmtree(case.crate_dir, ignore_errors=True)
        res.outcome = EMIT_FAIL
        res.detail = classify_emit_failure(res.emit_stderr)
        return res

    manifest = case.crate_dir / "Cargo.toml"
    src_dir = case.crate_dir / "src"
    rs = list(src_dir.glob("*.rs")) if src_dir.is_dir() else []
    if not manifest.is_file() or not rs:
        shutil.rmtree(case.crate_dir, ignore_errors=True)
        res.outcome, res.detail = EMIT_FAIL, "emit-empty (rc=0 but no crate written)"
        return res

    # The corpus root is a cargo workspace that does not list translated_rust;
    # without this opt-out cargo refuses to build the crate at all.
    with manifest.open("a", encoding="utf-8") as fh:
        fh.write("\n[workspace]\n")

    res.outcome = ""  # decided by the corpus runner
    return res


def classify_emit_failure(stderr: str) -> str:
    """Bucket a located rejection so the failure table is rankable."""
    for line in stderr.splitlines():
        m = re.search(r"(?:fatal error|error): (.+)", line)
        if not m:
            continue
        text = m.group(1).strip()
        if text == "failed to parse one or more C inputs":
            continue  # a summary of an earlier, more specific diagnostic
        if "file not found" in text:
            return "emit: missing header (" + text.split("'")[1] + ")" \
                if "'" in text else "emit: missing header"
        return "emit: " + text[:160]
    return "emit: rejected"


# ------------------------------------------------------------- corpus runner


def run_corpus(corpus: Path, junit: Path, extra: list, verbose: bool,
               jobs: Optional[int], log: Path) -> tuple:
    """Invoke the corpus's OWN runner. Returns (returncode, combined output)."""
    script = corpus / "deployment" / "scripts" / "github-actions" / "run_rust.sh"
    if not script.is_file():
        sys.exit(f"error: corpus runner not found at {script}")
    cmd = ["bash", str(script), "--root", str(corpus), "-s", "Public-Tests",
           "--keep-going", "--no-color", "-x", str(junit),
           "--build-timeout", str(BUILD_TIMEOUT),
           "--test-timeout", str(TEST_TIMEOUT)]
    if jobs:
        cmd += ["-j", str(jobs)]
    if verbose:
        cmd.append("--verbose")
    cmd += extra
    proc = subprocess.run(cmd, cwd=str(corpus), capture_output=True, text=True)
    log.write_text((proc.stdout or "") + "\n--- stderr ---\n" + (proc.stderr or ""),
                   encoding="utf-8")
    return proc.returncode, (proc.stdout or "") + (proc.stderr or "")


def parse_junit(path: Path) -> dict:
    """Return {case_rel_name: {"build": ..., "execution": ..., "vectors": [...]}}.

    The corpus emits one ``<testsuite>`` per case whose ``<testcase>`` entries
    are the phases it got through ("build", "build_lib_harness") followed by
    one entry per test vector. A phase entry carries ``<error>``, a vector
    carries ``<failure>`` or ``<skipped>``.
    """
    out = {}
    if not path.is_file():
        return out
    tree = ET.parse(path)
    for suite in tree.getroot().findall("testsuite"):
        name = suite.get("name")
        rec = {"build": None, "execution": None, "vectors": []}
        for tc in suite.findall("testcase"):
            tname = tc.get("name")
            err = tc.find("error")
            fail = tc.find("failure")
            skip = tc.find("skipped")
            if tname in ("build", "configure", "build_lib_harness"):
                if err is not None:
                    rec["build"] = err.get("message", "build failed")
                continue
            if tname == "execution":
                if err is not None:
                    rec["execution"] = err.get("message", "execution failed")
                continue
            if err is not None:
                # A phase-shaped error under a vector name still means the
                # subject could not be run.
                rec["execution"] = err.get("message", "error")
                continue
            if skip is not None:
                rec["vectors"].append((tname, "skipped", skip.get("message", "")))
            elif fail is not None:
                rec["vectors"].append((tname, "failed", fail.get("message", "")))
            else:
                rec["vectors"].append((tname, "passed", ""))
        out[name] = rec
    return out


def classify(res: Result, rec: Optional[dict]) -> None:
    """Fold the corpus runner's verdict into a per-case outcome."""
    if res.outcome == EMIT_FAIL:
        res.detail = res.detail_prefix + res.detail
        return
    if rec is None:
        res.outcome = NOT_DISCOVERED
        res.detail = "emitted, but the corpus runner did not discover the case"
        return
    if rec["build"]:
        res.outcome = BUILD_FAIL
        res.detail = "cargo: " + str(rec["build"])[:200]
        return
    if rec["execution"]:
        msg = str(rec["execution"])
        res.outcome = HARNESS_ERROR
        low = msg.lower()
        if "timed out" in low:
            res.detail = "timeout"
        elif "cannot open shared object" in low or "libloading" in low:
            res.detail = "dlopen failure"
        elif "undefined symbol" in low or "symbol" in low:
            res.detail = "dlsym failure"
        elif "no such file" in low:
            res.detail = "subject binary missing"
        else:
            res.detail = "runner error"
        res.detail += ": " + msg[:200]
        return
    for name, status, message in rec["vectors"]:
        if status == "passed":
            res.vectors_passed += 1
        elif status == "skipped":
            res.vectors_skipped += 1
        else:
            res.vectors_failed += 1
            res.vector_failures.append((name, message))
    if not rec["vectors"]:
        # The runner found no vectors at all -- never a pass.
        res.outcome = HARNESS_ERROR
        res.detail = "no test vectors were run"
        return
    if res.vectors_failed:
        # GUARD: the corpus's LibRunner reports a dlsym panic as an ordinary
        # vector failure -- the same "cando state mismatch" text a wrong
        # answer produces. Attributing that to WRONG OUTPUT would invent a
        # miscompile out of a missing export, so a case whose artifact does
        # not define the symbol the harness dlsyms is bucketed separately.
        # The verdict is still the corpus's (the case failed); only the
        # reason is ours. It matters more than it looks: when the symbol is
        # also a libc name, dlsym silently binds the harness to LIBC's
        # function instead of failing, and the case then "runs" and gives
        # wrong answers that have nothing to do with the emitted Rust.
        if res.case.is_library and res.symbol_present is False:
            res.outcome = SYMBOL_MISSING
            res.detail = (f"the emitted lib{res.case.library}.so defines no "
                          f"symbol {res.case.symbol!r}")
        elif not res.artifact:
            res.outcome = SYMBOL_MISSING
            res.detail = "the expected build artifact does not exist"
        else:
            res.outcome = VECTOR_FAIL
            res.detail = f"{res.vectors_failed} vector(s) mismatched"
    elif res.vectors_passed == 0:
        # GUARD: every vector was has_ub-skipped, so nothing was executed and
        # nothing was compared. The corpus's own summary counts such a case as
        # not-failed; counting it as behavioural equivalence would be exactly
        # the zero-iteration inflation this harness exists to prevent.
        res.outcome = VACUOUS_PASS
        res.detail = (f"all {res.vectors_skipped} vector(s) are has_ub and "
                      f"were skipped; nothing was executed")
    else:
        res.outcome = PASS
        res.detail = ""
    res.detail = res.detail_prefix + res.detail


def check_artifacts(res: Result) -> None:
    """Record what actually landed in target/release, for diagnosis only.

    This never changes an outcome -- the corpus runner owns the verdict. It
    exists so a dlsym failure can be attributed to a missing ``#[no_mangle]``
    export rather than to a wrong answer.
    """
    rel = res.case.crate_dir / "target" / "release"
    if res.case.is_library:
        so = rel / f"lib{res.case.library}.so"
        res.artifact = str(so) if so.is_file() else ""
        if so.is_file() and res.case.symbol:
            try:
                nm = subprocess.run(["nm", "-D", "--defined-only", str(so)],
                                    capture_output=True, text=True, timeout=60)
                res.symbol_present = any(
                    line.split()[-1] == res.case.symbol
                    for line in nm.stdout.splitlines() if line.split()
                )
            except (OSError, subprocess.TimeoutExpired):
                res.symbol_present = None
    else:
        drv = rel / "driver"
        res.artifact = str(drv) if drv.is_file() else ""


# ---------------------------------------------------------------- reporting


def diagnose_build_failure(res: Result) -> None:
    """Re-run cargo to capture the rustc diagnostics the corpus swallows.

    ``runtests/build.py`` builds with ``capture_output=False``, so the
    exception the corpus raises carries only "Command exited 101". This is a
    DIAGNOSIS ONLY -- the verdict stays the corpus's.
    """
    try:
        proc = subprocess.run(
            ["cargo", "build", "--release", "--target-dir",
             str(res.case.crate_dir / "target")],
            cwd=str(res.case.crate_dir), capture_output=True, text=True,
            timeout=BUILD_TIMEOUT)
    except (OSError, subprocess.TimeoutExpired) as exc:
        res.detail += f" | rebuild for diagnosis failed: {exc!r}"
        return
    errors = [l for l in (proc.stderr or "").splitlines()
              if l.startswith("error")]
    if errors:
        res.detail = "cargo: " + "; ".join(errors[:4])


def write_reports(out_dir: Path, results: list, skipped: list,
                  discovered: int) -> None:
    payload = {
        "denominator": len(results),
        "denominator_note": (
            "cases under Public-Tests with a test_vectors/ directory AND at "
            "least one .c under test_case/; the rest of the 252 public case "
            "directories ship no sources in the public clone and are not "
            "evaluable"
        ),
        "non_evaluable": len(skipped),
        "non_evaluable_cases": skipped,
        "discovered_by_corpus_runner": discovered,
        "cases": [r.as_dict() for r in results],
    }
    (out_dir / "results.json").write_text(json.dumps(payload, indent=2),
                                          encoding="utf-8")
    with (out_dir / "results.tsv").open("w", encoding="utf-8") as fh:
        fh.write("case\tkind\toutcome\tpassed\tfailed\tskipped\tdetail\n")
        for r in results:
            fh.write("\t".join([
                r.case.rel_name,
                "lib" if r.case.is_library else "exec",
                r.outcome,
                str(r.vectors_passed), str(r.vectors_failed),
                str(r.vectors_skipped),
                r.detail.replace("\t", " ").replace("\n", " ")[:300],
            ]) + "\n")


def summarize(results: list, skipped: list, out_dir: Path) -> None:
    n = len(results)
    libs = [r for r in results if r.case.is_library]
    execs = [r for r in results if not r.case.is_library]

    def npass(rs):
        return sum(1 for r in rs if r.outcome == PASS)

    print()
    print("=" * 72)
    print("TRACTOR criterion (a) -- behavioural equivalence, corpus oracle")
    print("=" * 72)
    print(f"denominator: {n} evaluable cases "
          f"({len(skipped)} case dirs excluded: no .c sources in the public clone)")
    print(f"  exec: {len(execs)}   _lib: {len(libs)}")
    print()
    print(f"CASES PASSING ALL VECTORS: {npass(results)}/{n} "
          f"({100.0 * npass(results) / n:.1f}%)")
    print(f"  exec: {npass(execs)}/{len(execs)}")
    print(f"  _lib: {npass(libs)}/{len(libs)}")
    vacuous = [r for r in results if r.outcome == VACUOUS_PASS]
    if vacuous:
        print(f"  (excludes {len(vacuous)} case(s) the corpus does not fail "
              f"but that executed nothing -- every vector has_ub-skipped: "
              + ", ".join(r.case.rel_name.split("/")[-1] for r in vacuous) + ")")
    print()
    vp = sum(r.vectors_passed for r in results)
    vf = sum(r.vectors_failed for r in results)
    vs = sum(r.vectors_skipped for r in results)
    print(f"VECTORS: passed={vp} failed={vf} skipped(has_ub)={vs}")
    glob = [r for r in results if r.source_mode == "glob"]
    if glob:
        print(f"NOTE: {len(glob)} case(s) fell back to globbed sources rather "
              f"than the case's own CMake flags")
    print()
    print("outcomes:")
    for outcome in OUTCOME_ORDER:
        rs = [r for r in results if r.outcome == outcome]
        if rs:
            e = sum(1 for r in rs if not r.case.is_library)
            print(f"  {outcome:<16} {len(rs):>4}   (exec {e}, lib {len(rs) - e})")
    print()
    print("ranked failure reasons:")
    reasons = {}
    for r in results:
        if r.outcome == PASS:
            continue
        key = (r.outcome, r.detail.split("\n")[0][:90])
        reasons[key] = reasons.get(key, 0) + 1
    for (outcome, detail), count in sorted(reasons.items(),
                                           key=lambda kv: -kv[1]):
        print(f"  {count:>4}  {outcome:<14} {detail}")

    wrong = [r for r in results if r.outcome == VECTOR_FAIL]
    if wrong:
        print()
        print("!" * 72)
        print(f"!! {len(wrong)} CASE(S) BUILT, RAN, AND PRODUCED WRONG OUTPUT "
              f"-- POTENTIAL MISCOMPILES")
        print("!" * 72)
        for r in wrong:
            print(f"\n  {r.case.rel_name}  "
                  f"({'lib' if r.case.is_library else 'exec'}, "
                  f"{r.vectors_passed} passed / {r.vectors_failed} failed)")
            for name, message in r.vector_failures:
                print(f"    vector {name}:")
                for line in (message or "").splitlines():
                    print(f"      {line}")
    print()
    print(f"reports: {out_dir}/results.json, {out_dir}/results.tsv, "
          f"{out_dir}/junit.xml")


