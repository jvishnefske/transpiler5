#!/usr/bin/env python3
"""TRACTOR corpus runner for emitrust-cc: criterion (a), behavioural equivalence.

The TRACTOR evaluation corpus (DARPA TRACTOR public tests) is NOT vendored --
it is cloned separately and its root is passed in as an argument. This harness
drives the corpus's OWN oracle; it deliberately does not reimplement the
input/output comparison, because the number that counts is the one the corpus's
runner produces:

    deployment/scripts/github-actions/run_rust.sh --root <corpus>

Pipeline, per evaluable case ``<corpus>/Public-Tests/<bundle>/<case>/``:

  1. EMIT   -- ``emitrust-cc --emit=crate`` writes ``<case>/translated_rust/``,
               the exact directory the corpus's Rust discovery profile looks
               for (``runtests/discovery/rust.py``). STRICT MODE ONLY: never
               ``--recover``, never ``--incremental``. The rubric awards no
               partial credit, so a partially translated crate is worth
               exactly as much as no crate at all and must not be counted.
  2. BUILD  -- left to the corpus runner (``runtests/build.py``:
               ``cargo build --release --target-dir <case>/translated_rust/target``).
  3. TEST   -- the corpus runner again, with ``RUST_ARTIFACTS`` set, so
               ``ExecRunner`` runs ``target/release/driver`` and ``LibRunner``
               runs the case's cando2 harness, which dlopens
               ``target/release/lib<LIBRARY>.so`` and dlsyms a BARE symbol.

Two adaptations to the corpus are unavoidable and are made explicit here
rather than hidden:

  * ``[workspace]`` is appended to every emitted ``Cargo.toml``. The corpus
    root is a cargo workspace whose members glob (``*-Tests/*/*_lib/runner``)
    does not cover ``translated_rust``, so cargo refuses to build an emitted
    crate ("current package believes it's in a workspace when it's not")
    until the crate opts out. Every performer must do this; it changes no
    emitted Rust.
  * Every case is emitted from a ``compile_commands.json`` generated by
    configuring the case's OWN CMake project, filtered down to the exact
    CMake target the corpus tests (``driver`` for an exec case, the cando2
    ``library`` name for a ``_lib`` case) and that target's transitive link
    closure, read out of CMake's file API. Globbing ``test_case/src/*.c``
    is wrong for a third of the corpus: the SPHINCS+ bundle compiles ONE
    shared source tree into 128 different cases, selected by
    ``CMakePresets.json`` cache variables (``HASH_BACKEND``, ``SECPAR``,
    ``THASH``) that turn into ``-D`` macros. ``emitrust-cc`` accepts no
    ``-D``, so the compile database is the only vehicle for them. A glob
    fallback (``test_case/src/*.c`` plus ``-I test_case/include``) is used
    only if CMake configuration fails.

NAMING. The corpus's expectations about the shared object and the symbol are
NOT uniformly derivable, so they are read out of each ``_lib`` case's own
harness rather than guessed:

  * long form -- ``runner/src/main.rs`` pins ``library: "..."`` and
    ``symbol: "..."`` explicitly (all 42 ``B01_synthetic`` ``_lib`` cases;
    e.g. ``004_nineality_sieve_lib`` wants ``libSieve.so`` / ``sieve``).
  * short form -- no such lines, and cando2's ``harness!`` defaults to
    ``library = CANDIDATE_NAME`` (the case directory name) and
    ``symbol = CANDIDATE_SYMBOL_NAME`` (that name minus ``_lib``); this is
    the 38 ``B01_organic`` cases.

``--crate-name`` is set to that LIBRARY name, which FR-139 passes through
verbatim when it is already a usable Rust identifier, so ``Sieve`` really does
produce ``libSieve.so``; ``--c-abi-exports`` gives the all-scalar exported
functions the bare ``#[no_mangle] extern "C"`` symbols the harness dlsyms.
Exec cases are emitted with ``--crate-name=driver`` because
``runners/exec_runner.py`` runs a binary literally named ``driver``.

HONESTY GUARDS. This ledger has twice reported an inflated numerator, once
because a case with no sources ran a per-source loop zero times and fell
through to "all passed". The guards are:

  * DISCOVERY. A case is EVALUABLE only if it has a ``test_vectors/``
    directory AND at least one ``.c`` file reachable under ``test_case/``.
    "Reachable" matters: in 127 of the 252 public cases ``test_case`` is a
    SYMLINK to a sibling case's tree, and a source scan that does not follow
    symlinks reports them as empty. They are not empty. The denominator for
    every rate in the report is the evaluable count, printed with it, and any
    case that really has no sources is excluded from it and reported
    separately -- never as a success.
  * EMPTY EMIT. A case whose source list is empty is failed as
    ``no-sources`` before ``emitrust-cc`` is ever invoked, and a case whose
    emit succeeds but leaves no ``src/*.rs`` is failed as ``emit-empty``.
    Both are structurally incapable of reaching the corpus runner.
  * EXIT CODES. ``emitrust-cc`` exits 1 having done nothing on an unknown
    flag, which is indistinguishable from success by output inspection, so
    every invocation is checked by return code AND by the existence of its
    output.
  * NO STALE ARTIFACTS. ``<case>/translated_rust`` is deleted whole (target
    directory included) before each run. A shared object left behind by an
    earlier run under a different ``--crate-name`` would otherwise be
    dlopened and scored.
  * DID-NOT-RUN vs RAN-AND-FAILED. A case that never emitted has no
    ``translated_rust`` and is therefore not even discovered by the corpus
    runner. The report keeps ``emit-failed``, ``build-failed``,
    ``harness-error`` (dlopen/dlsym/spawn/timeout) and ``vector-failed``
    (built, ran, produced the wrong bytes) as four separate facts and never
    merges them.

Reported outcomes, per case:

  ``PASS``          -- discovered by the corpus runner, built, and every one
                       of its test vectors passed, with AT LEAST ONE vector
                       actually executed. This all-or-nothing figure is the
                       criterion-(a) number.
  ``VACUOUS_PASS``  -- the corpus does not fail the case, but every vector it
                       has is ``has_ub`` and was skipped, so nothing ran and
                       nothing was compared. Never counted as a pass.
  ``VECTOR_FAIL``   -- built, the artifact really exports what the harness
                       needs, it ran, and at least one vector's stdout/stderr/
                       rc (or, for ``_lib``, the cando2 state) differed. THESE
                       ARE THE POTENTIAL MISCOMPILES and are listed
                       individually, with the corpus runner's own diff,
                       obtained by re-running just those cases with
                       ``--verbose --only test``.
  ``SYMBOL_MISSING``-- the corpus failed the case, but the emitted artifact
                       does not define the symbol the harness dlsyms (or does
                       not exist). Kept out of ``VECTOR_FAIL`` because a
                       missing export is not a wrong answer -- and because
                       when the symbol happens to be a libc name (``wcscat``),
                       ``dlsym`` binds the harness to LIBC's function through
                       the cdylib's dependency chain instead of failing, so
                       the case appears to run and produce garbage that has
                       nothing to do with the emitted Rust.
  ``HARNESS_ERROR`` -- the runner could not run the subject at all: dlopen
                       failure, missing ``driver``, spawn error, or a test
                       timeout.
  ``BUILD_FAIL``    -- the crate was emitted but ``cargo build`` rejected it.
  ``EMIT_FAIL``     -- ``emitrust-cc`` refused the input (a located rejection,
                       which is a feature) or crashed.
  ``NOT_DISCOVERED``-- emitted, but the corpus runner did not pick the case
                       up. Always a harness bug; reported loudly, never
                       silently dropped.

Outputs, written to ``--out`` (default ``<corpus>/../tractor-eval-out``):

  ``results.json``  -- the full per-case, per-vector record.
  ``results.tsv``   -- one line per case: name, kind, outcome, counts, detail.
  ``junit.xml``     -- the corpus runner's own report, unmodified.
  plus a human summary on stdout.

Modeled on ``test/RealWorld/run_realworld.py`` (the closest analogue in this
tree: an external-corpus runner with a ledger).
"""

