def parse_lib_naming(case_root: Path) -> tuple:
    """Return (library, symbol, naming) for a ``_lib`` case.

    The long ``harness!`` form pins both names in ``runner/src/main.rs``; the
    short form falls back to cando2's defaults, which are derived from the
    case directory name. Guessing either one wrong produces a dlopen or dlsym
    panic that looks like a translation failure, so this is read, not assumed.
    """
    name = case_root.name
    derived = (name, name[: -len("_lib")] if name.endswith("_lib") else name)
    main_rs = case_root / "runner" / "src" / "main.rs"
    if not main_rs.is_file():
        return derived[0], derived[1], "derived"
    text = main_rs.read_text(encoding="utf-8", errors="replace")
    lib = _LIBRARY_RX.search(text)
    sym = _SYMBOL_RX.search(text)
    if lib and sym:
        return lib.group(1), sym.group(1), "explicit"
    return derived[0], derived[1], "derived"


def discover(corpus: Path) -> tuple:
    """Return (evaluable cases, skipped rel_names).

    A directory under ``Public-Tests/<bundle>/`` is a case if it has a
    ``test_vectors/`` directory. It is EVALUABLE only if it also has at least
    one ``.c`` file REACHABLE under ``test_case/`` -- reachable, because in
    127 of the 252 public cases ``test_case`` is a symlink into a sibling
    case's tree, and a scan that stops at symlinks reports those cases as
    sourceless when they are not.
    """
    cases, skipped = [], []
    public = corpus / "Public-Tests"
    if not public.is_dir():
        sys.exit(f"error: {public} does not exist -- is {corpus} a TRACTOR corpus?")
    for bundle in sorted(p for p in public.iterdir() if p.is_dir()):
        for root in sorted(p for p in bundle.iterdir() if p.is_dir()):
            if not (root / "test_vectors").is_dir():
                continue
            rel = str(root.relative_to(corpus))
            test_case = root / "test_case"
            sources = sorted(
                p for p in test_case.rglob("*.c")
                if not any(part in ("build", "build-ninja", "target",
                                    "translated_rust")
                           for part in p.relative_to(test_case).parts)
            ) if test_case.is_dir() else []
            if not sources:
                skipped.append(rel)
                continue
            includes = sorted({str(p) for p in test_case.rglob("include")
                               if p.is_dir()})
            includes += sorted({str(p.parent) for p in sources})
            is_lib = root.name.endswith("_lib")
            lib = sym = None
            naming = "n/a"
            if is_lib:
                lib, sym, naming = parse_lib_naming(root)
            # A case root with its own CMakeLists.txt is a CI wrapper that
            # parameterizes test_case through cache variables (the SPHINCS+
            # shape); configure from there, not from test_case, or the
            # parameters are lost.
            cmake_src = root if (root / "CMakeLists.txt").is_file() else test_case
            cases.append(Case(rel_name=rel, root=root, is_library=is_lib,
                              glob_sources=[str(p) for p in sources],
                              glob_include_dirs=includes, library=lib,
                              symbol=sym, naming=naming,
                              cmake_source_dir=cmake_src,
                              cache_vars=preset_cache_vars(root)))
    return cases, skipped


